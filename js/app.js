const nav = document.getElementById("nav");
const menuBtn = document.getElementById("menuBtn");
const year = document.getElementById("year");
const form = document.getElementById("bookForm");
const formNote = document.getElementById("formNote");
const lightbox = document.getElementById("lightbox");
const lightboxImg = lightbox.querySelector("img");
const slides = [...document.querySelectorAll(".hero__slide")];
const dotsWrap = document.getElementById("heroDots");

let lang = localStorage.getItem("mir-lang") || "hr";
let slide = 0;
let timer;

year.textContent = new Date().getFullYear();

function setLang(next) {
  lang = next;
  localStorage.setItem("mir-lang", lang);
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (i18n[lang][key]) el.textContent = i18n[lang][key];
  });
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.classList.toggle("is-active", btn.dataset.lang === lang);
  });
  document.title = i18n[lang]["page.title"];
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", i18n[lang]["page.desc"]);
}

function go(index) {
  slide = (index + slides.length) % slides.length;
  slides.forEach((el, i) => el.classList.toggle("is-active", i === slide));
  [...dotsWrap.children].forEach((el, i) => el.classList.toggle("is-active", i === slide));
}

function play() {
  clearInterval(timer);
  timer = setInterval(() => go(slide + 1), 6500);
}

slides.forEach((_, i) => {
  const b = document.createElement("button");
  b.type = "button";
  b.setAttribute("aria-label", `Slide ${i + 1}`);
  b.addEventListener("click", () => {
    go(i);
    play();
  });
  dotsWrap.append(b);
});

go(0);
play();

document.querySelector(".hero").addEventListener("mouseenter", () => clearInterval(timer));
document.querySelector(".hero").addEventListener("mouseleave", play);

window.addEventListener("scroll", () => {
  nav.classList.toggle("is-solid", window.scrollY > 40);
});

menuBtn.addEventListener("click", () => nav.classList.toggle("is-open"));
document.querySelectorAll(".nav__links a").forEach((a) => {
  a.addEventListener("click", () => nav.classList.remove("is-open"));
});

document.querySelectorAll("[data-lang]").forEach((btn) => {
  btn.addEventListener("click", () => setLang(btn.dataset.lang));
});

document.querySelectorAll("#gallery button").forEach((btn) => {
  btn.addEventListener("click", () => {
    const img = btn.querySelector("img");
    lightboxImg.src = img.src;
    lightboxImg.alt = img.alt;
    lightbox.classList.add("is-open");
  });
});

function closeLightbox() {
  lightbox.classList.remove("is-open");
  lightboxImg.src = "";
}

document.getElementById("lightboxClose").addEventListener("click", closeLightbox);
lightbox.addEventListener("click", (e) => {
  if (e.target === lightbox) closeLightbox();
});
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") closeLightbox();
});

form.addEventListener("submit", (e) => {
  e.preventDefault();
  const data = Object.fromEntries(new FormData(form));
  const subject = encodeURIComponent(`Rezervacija MIR — ${data.apt} (${data.arrive} / ${data.leave})`);
  const body = encodeURIComponent(
    [
      `Ime: ${data.name}`,
      `E-pošta: ${data.email}`,
      `Dolazak: ${data.arrive}`,
      `Odlazak: ${data.leave}`,
      `Osobe: ${data.guests}`,
      `Apartman: ${data.apt}`,
      "",
      data.note || "",
    ].join("\n")
  );
  window.location.href = `mailto:jure.jerkic@tel.net.ba?subject=${subject}&body=${body}`;
  formNote.textContent = i18n[lang]["form.ok"];
  formNote.classList.add("is-ok");
});

setLang(lang);
