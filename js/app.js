function isEmail(value) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value);
}

function validateForm() {
  const name = form.elements.name;
  const email = form.elements.email;
  const arrive = form.elements.arrive;
  const leave = form.elements.leave;
  const guests = form.elements.guests;
  const apt = form.elements.apt;
  const checks = [
    [name, name.value.trim().length > 1],
    [email, isEmail(email.value.trim())],
    [arrive, Boolean(arrive.value)],
    [leave, Boolean(leave.value) && (!arrive.value || leave.value >= arrive.value)],
    [guests, Number(guests.value) >= 1 && Number(guests.value) <= 10],
    [apt, Boolean(apt.value)],
    [form.elements.consent, form.elements.consent.checked],
  ];

  let firstInvalid = null;
  checks.forEach(([el, ok]) => {
    markField(el, !ok);
    if (!ok && !firstInvalid) firstInvalid = el;
  });

  if (firstInvalid) {
    showFormNote("is-err", t(firstInvalid.name === "consent" ? "form.consentErr" : "form.invalid"));
    firstInvalid.focus();
    return false;
  }
  return true;
}

